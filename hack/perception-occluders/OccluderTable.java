import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import net.minecraft.DetectedVersion;
import net.minecraft.SharedConstants;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.Property;

/**
 * Writes the Go occluder table used by `perception extract`.
 *
 * The table records vanilla BlockState.isSolidRender() for every registered
 * block state: the same predicate vanilla uses to cull faces hidden behind an
 * opaque full cube. A block is "solid" when all of its states are, "open" when
 * none are, and conditional when exactly one property value separates them.
 */
public final class OccluderTable {
    private OccluderTable() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 1) {
            throw new IllegalArgumentException("usage: OccluderTable <output.go>");
        }
        SharedConstants.setVersion(DetectedVersion.BUILT_IN);
        Bootstrap.bootStrap();
        TreeSet<String> solid = new TreeSet<>();
        TreeSet<String> open = new TreeSet<>();
        TreeMap<String, String[]> conditional = new TreeMap<>();
        for (Block block : BuiltInRegistries.BLOCK) {
            String name = BuiltInRegistries.BLOCK.getKey(block).toString();
            List<BlockState> states = block.getStateDefinition().getPossibleStates();
            long solidCount = states.stream().filter(BlockState::isSolidRender).count();
            if (solidCount == states.size()) {
                solid.add(name);
            } else if (solidCount == 0) {
                open.add(name);
            } else {
                conditional.put(name, separatingValue(name, states));
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("// Code generated by hack/generate-perception-occluders; DO NOT EDIT.\n\n");
        out.append("package perceptions\n\n");
        out.append("// occluderTableVersion is the Minecraft version whose block registry produced this table.\n");
        out.append("const occluderTableVersion = \"").append(SharedConstants.getCurrentVersion().name()).append("\"\n\n");
        out.append("// solidRenderBlocks lists blocks whose every state is an opaque full cube.\n");
        writeSet(out, "solidRenderBlocks", solid);
        out.append("\n// openBlocks lists blocks with no opaque full-cube state.\n");
        writeSet(out, "openBlocks", open);
        out.append("\n// conditionalSolidRenderBlocks lists blocks that are an opaque full cube\n");
        out.append("// exactly when one property has one value.\n");
        out.append("var conditionalSolidRenderBlocks = map[string]blockStateCondition{\n");
        for (Map.Entry<String, String[]> entry : conditional.entrySet()) {
            out.append("\t\"").append(entry.getKey()).append("\": {property: \"").append(entry.getValue()[0])
                .append("\", value: \"").append(entry.getValue()[1]).append("\"},\n");
        }
        out.append("}\n");
        Files.writeString(Path.of(args[0]), out.toString(), StandardCharsets.UTF_8);
    }

    private static void writeSet(StringBuilder out, String name, TreeSet<String> values) {
        out.append("var ").append(name).append(" = map[string]struct{}{\n");
        for (String value : values) {
            out.append("\t\"").append(value).append("\": {},\n");
        }
        out.append("}\n");
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private static String[] separatingValue(String name, List<BlockState> states) {
        List<String[]> candidates = new ArrayList<>();
        for (Property property : states.get(0).getProperties()) {
            for (Object value : property.getPossibleValues()) {
                boolean separates = true;
                for (BlockState state : states) {
                    boolean matches = state.getValue(property).equals(value);
                    if (matches != state.isSolidRender()) {
                        separates = false;
                        break;
                    }
                }
                if (separates) {
                    candidates.add(new String[]{property.getName(), property.getName((Comparable) value)});
                }
            }
        }
        if (candidates.size() != 1) {
            throw new IllegalStateException(name + " has no single property value that decides solid rendering");
        }
        return candidates.get(0);
    }
}
